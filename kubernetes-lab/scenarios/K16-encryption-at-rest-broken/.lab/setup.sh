# K16: --encryption-provider-config on a file the container can't see, with a 31-byte aescbc key
kns payments
kx -n payments create secret generic stripe-key --from-literal=key="sk_live_$(openssl rand -hex 12)" --dry-run=client -o yaml | ka -f -
nxi "$CP" >/dev/null <<'__X__'
set -eu
mkdir -p /etc/kubernetes/enc
key=$(head -c 31 /dev/urandom | base64)        # "32 characters" - generated by hand
cat > /etc/kubernetes/enc/enc.yaml <<EOF
apiVersion: apiserver.config.k8s.io/v1
kind: EncryptionConfiguration
resources:
  - resources: [secrets]
    providers:
      - aescbc:
          keys:
            - {name: key1, secret: $key}
      - identity: {}
EOF
chmod 600 /etc/kubernetes/enc/enc.yaml
python3 - <<'PY'
import yaml
f = "/etc/kubernetes/manifests/kube-apiserver.yaml"; d = yaml.safe_load(open(f))
d["spec"]["containers"][0]["command"].append("--encryption-provider-config=/etc/kubernetes/enc/enc.yaml")
yaml.safe_dump(d, open("/var/tmp/kube-apiserver.yaml", "w"), sort_keys=False)
PY
mv /var/tmp/kube-apiserver.yaml /etc/kubernetes/manifests/kube-apiserver.yaml
__X__
api_down() { ! KX_TIMEOUT=5s kx get --raw /readyz >/dev/null 2>&1; }
retry 180 api_down || die "the API server did not go down"
