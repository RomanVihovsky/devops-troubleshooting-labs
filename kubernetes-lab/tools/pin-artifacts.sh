#!/usr/bin/env bash
# pin-artifacts.sh - resolve every file the cluster needs (from versions.env) to "name url sha256" lines in
# infra/artifacts.txt. Big files take their checksum from the upstream checksum file; small ones (manifests,
# charts, the containerd unit) are downloaded and hashed. gw's sync.sh downloads exactly these and verifies.
set -euo pipefail
LAB_DIR="$(cd "$(dirname "$0")/.." && pwd)"
# shellcheck source=versions.env source-path=SCRIPTDIR/..
source "$LAB_DIR/versions.env"
OUT="$LAB_DIR/infra/artifacts.txt"
GH=https://github.com
RAW=https://raw.githubusercontent.com
# Every download is cached in cache/pin (by URL), so a rerun only goes online for URLs it hasn't seen -
# one flaky host doesn't break a re-pin. --refresh empties the cache first.
PIN_CACHE="$LAB_DIR/cache/pin"
[ "${1:-}" = --refresh ] && rm -rf "$PIN_CACHE"
mkdir -p "$PIN_CACHE"
cached() {   # url -> path of the cached copy (downloaded on first use)
  local f; f="$PIN_CACHE/$(printf '%s' "$1" | sha256sum | cut -c1-40)"
  if [ ! -s "$f" ]; then
    curl -fsSL --retry 4 --retry-connrefused --retry-delay 5 --max-time 180 -o "$f.part" "$1" >&2 || { rm -f "$f.part"; return 1; }
    mv "$f.part" "$f"
  fi
  echo "$f"
}
get()  { local f; f=$(cached "$1") && cat "$f"; }
hash_url() { local f; f=$(cached "$1") && sha256sum "$f" | cut -d' ' -f1; }
# sum_from <checksum-file-url> <file name in it>
sum_from() { get "$1" | awk -v f="$2" '{ n = $2; sub(/^\*/, "", n); sub(/^.*\//, "", n) } !found && n == f { print $1; found = 1 }'; }
# chart_url <repo index url> <chart> <version>
chart_url() {
  get "$1" | python3 -c '
import sys, yaml, urllib.parse
idx = yaml.safe_load(sys.stdin); base, name, ver = sys.argv[1], sys.argv[2], sys.argv[3]
for e in idx["entries"][name]:
    if e["version"].lstrip("v") == ver.lstrip("v"):
        print(urllib.parse.urljoin(base, e["urls"][0])); break
else:
    sys.exit("chart %s %s not in %s" % (name, ver, base))' "$1" "$2" "$3"
}
line() { [ -n "$3" ] || { echo "no checksum for $1" >&2; exit 1; }; printf '%s %s %s\n' "$1" "$2" "$3"; echo "  $1" >&2; }

{
  echo "# generated by tools/pin-artifacts.sh from versions.env - name url sha256 (served by gw at $GW_FILES/files/<name>)"
  u=$GH/containerd/containerd/releases/download/v$CONTAINERD_VERSION/containerd-$CONTAINERD_VERSION-linux-amd64.tar.gz
  line "containerd-$CONTAINERD_VERSION-linux-amd64.tar.gz" "$u" "$(sum_from "$u.sha256sum" "${u##*/}")"
  u=$RAW/containerd/containerd/v$CONTAINERD_VERSION/containerd.service
  line "containerd-$CONTAINERD_VERSION.service" "$u" "$(hash_url "$u")"
  u=$GH/opencontainers/runc/releases/download/v$RUNC_VERSION/runc.amd64
  line "runc-$RUNC_VERSION.amd64" "$u" "$(sum_from "${u%/*}/runc.sha256sum" runc.amd64)"
  u=$GH/etcd-io/etcd/releases/download/v$ETCD_TOOLS_VERSION/etcd-v$ETCD_TOOLS_VERSION-linux-amd64.tar.gz
  line "${u##*/}" "$u" "$(sum_from "${u%/*}/SHA256SUMS" "${u##*/}")"
  u=$GH/distribution/distribution/releases/download/v$REGISTRY_VERSION/registry_${REGISTRY_VERSION}_linux_amd64.tar.gz
  line "${u##*/}" "$u" "$(get "$u.sha256" | awk 'NR == 1 { print $1 }')"
  u=$GH/google/go-containerregistry/releases/download/v$CRANE_VERSION/go-containerregistry_Linux_x86_64.tar.gz
  line "crane-$CRANE_VERSION-linux-amd64.tar.gz" "$u" "$(sum_from "${u%/*}/checksums.txt" "${u##*/}")"
  u=https://get.helm.sh/helm-v$HELM_VERSION-linux-amd64.tar.gz
  line "${u##*/}" "$u" "$(get "$u.sha256sum" | cut -d' ' -f1)"

  u=$RAW/projectcalico/calico/v$CALICO_VERSION/manifests/calico.yaml
  line "calico-$CALICO_VERSION.yaml" "$u" "$(hash_url "$u")"
  u=$GH/kubernetes-sigs/gateway-api/releases/download/v$GATEWAY_API_VERSION/standard-install.yaml
  line "gateway-api-$GATEWAY_API_VERSION-standard.yaml" "$u" "$(hash_url "$u")"
  u=$RAW/rancher/local-path-provisioner/v$LOCAL_PATH_VERSION/deploy/local-path-storage.yaml
  line "local-path-$LOCAL_PATH_VERSION.yaml" "$u" "$(hash_url "$u")"
  for f in volumesnapshotclasses volumesnapshotcontents volumesnapshots; do
    u=$RAW/kubernetes-csi/external-snapshotter/v$SNAPSHOTTER_VERSION/client/config/crd/snapshot.storage.k8s.io_$f.yaml
    line "snapshot-$SNAPSHOTTER_VERSION-crd-$f.yaml" "$u" "$(hash_url "$u")"
  done
  for f in rbac-snapshot-controller setup-snapshot-controller; do
    u=$RAW/kubernetes-csi/external-snapshotter/v$SNAPSHOTTER_VERSION/deploy/kubernetes/snapshot-controller/$f.yaml
    line "snapshot-$SNAPSHOTTER_VERSION-$f.yaml" "$u" "$(hash_url "$u")"
  done

  u=$(chart_url https://metallb.github.io/metallb/index.yaml metallb "$METALLB_CHART_VERSION")
  line "metallb-$METALLB_CHART_VERSION.tgz" "$u" "$(hash_url "$u")"
  u=$(chart_url https://traefik.github.io/charts/index.yaml traefik "$TRAEFIK_CHART_VERSION")
  line "traefik-$TRAEFIK_CHART_VERSION.tgz" "$u" "$(hash_url "$u")"
  u=$(chart_url https://kubernetes-sigs.github.io/metrics-server/index.yaml metrics-server "$METRICS_SERVER_CHART_VERSION")
  line "metrics-server-$METRICS_SERVER_CHART_VERSION.tgz" "$u" "$(hash_url "$u")"
  u=$(chart_url $RAW/kubernetes-csi/csi-driver-nfs/master/charts/index.yaml csi-driver-nfs "$CSI_NFS_CHART_VERSION")
  line "csi-driver-nfs-$CSI_NFS_CHART_VERSION.tgz" "$u" "$(hash_url "$u")"

  # ---- Phase 2: GitOps + secrets
  u=$GH/argoproj/argo-cd/releases/download/v$ARGOCD_VERSION/argocd-linux-amd64
  line "argocd-$ARGOCD_VERSION-linux-amd64" "$u" "$(sum_from "${u%/*}/cli_checksums.txt" argocd-linux-amd64)"
  u=$GH/bitnami/sealed-secrets/releases/download/v$SEALED_SECRETS_VERSION/kubeseal-$SEALED_SECRETS_VERSION-linux-amd64.tar.gz
  line "${u##*/}" "$u" "$(sum_from "${u%/*}/sealed-secrets_${SEALED_SECRETS_VERSION}_checksums.txt" "${u##*/}")"
  u=$GH/openbao/openbao/releases/download/v$OPENBAO_VERSION/openbao_${OPENBAO_VERSION}_linux_amd64.deb
  line "${u##*/}" "$u" "$(sum_from "${u%/*}/checksums.txt" "${u##*/}")"
  u=$GH/go-gitea/gitea/releases/download/v$GITEA_VERSION/gitea-$GITEA_VERSION-linux-amd64
  line "${u##*/}" "$u" "$(get "$u.sha256" | awk 'NR == 1 { print $1 }')"
  u=$GH/getsops/sops/releases/download/v$SOPS_VERSION/sops-v$SOPS_VERSION.linux.amd64
  line "${u##*/}" "$u" "$(sum_from "${u%/*}/sops-v$SOPS_VERSION.checksums.txt" "${u##*/}")"
  u=$GH/FiloSottile/age/releases/download/v$AGE_VERSION/age-v$AGE_VERSION-linux-amd64.tar.gz
  line "${u##*/}" "$u" "$(hash_url "$u")"
  u=$(chart_url https://argoproj.github.io/argo-helm/index.yaml argo-cd "$ARGOCD_CHART_VERSION")
  line "argo-cd-$ARGOCD_CHART_VERSION.tgz" "$u" "$(hash_url "$u")"
  u=$(chart_url https://bitnami.github.io/sealed-secrets/index.yaml sealed-secrets "$SEALED_SECRETS_CHART_VERSION")
  line "sealed-secrets-$SEALED_SECRETS_CHART_VERSION.tgz" "$u" "$(hash_url "$u")"
  u=$(chart_url https://charts.external-secrets.io/index.yaml external-secrets "$ESO_CHART_VERSION")
  line "external-secrets-$ESO_CHART_VERSION.tgz" "$u" "$(hash_url "$u")"
} > "$OUT.new"
mv "$OUT.new" "$OUT"
echo "wrote ${OUT#"$LAB_DIR"/}: $(grep -vc '^#' "$OUT") artifacts"
