# shellcheck shell=bash disable=SC2029,SC2016,SC2153,SC2034
# SC2029/SC2016: remote commands are built on purpose ($vars in single quotes expand on the node);
# SC2153/SC2034: PYCDLIB_* come from versions.env, CHECKS_FAILED belongs to lib/common.sh.
# The lab VMs are sibling VirtualBox VMs created on the physical host by the kit (infra/vbox:
# k8slab.bat / k8slab.sh). ./lab only reaches them over SSH on the host-only network 192.168.56.0/24.

NODES_CSV="$LAB_DIR/infra/vbox/nodes.csv"
LAB_KEY="$STATE_DIR/labvm_key"
KIT_DIR="$STATE_DIR/kit"
SHARED_KIT=${K8SLAB_SHARED_KIT:-/home/shared/k8slab-kit}
PYCDLIB_WHL="$CACHE_DIR/pypi/pycdlib-$PYCDLIB_VERSION-py3-none-any.whl"

# node_rows -> "name cpus mem ip mac1 mac2 role" per node (comments and CRs dropped)
node_rows() { awk -F, '!/^#/ && NF >= 7 { gsub(/\r/, ""); print $1, $2, $3, $4, $5, $6, $7 }' "$NODES_CSV"; }
node_name() { case $1 in k8s-*) echo "$1" ;; *) echo "k8s-$1" ;; esac; }
node_ip()   { node_rows | awk -v n="$(node_name "$1")" '$1 == n { print $4 }'; }
node_field() { node_rows | awk -v n="$(node_name "$1")" -v f="$2" '$1 == n { print $f }'; }
active_nodes() { node_rows | awk '$7 != "spare" { print $1 }'; }
# nodes_or_default [names...]: the names given (validated), or every non-spare node
nodes_or_default() {
  local n
  if [ $# -eq 0 ]; then active_nodes; return; fi
  for n in "$@"; do [ -n "$(node_ip "$n")" ] || die "unknown node: $n (see infra/vbox/nodes.csv)"; node_name "$n"; done
}

# Host keys change whenever a VM is re-created; the host-only network is private, so don't pin them.
ssh_opts() {
  echo -i "$LAB_KEY" -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null -o LogLevel=ERROR \
       -o ConnectTimeout=4 -o ServerAliveInterval=15 -o BatchMode=yes
}
# nssh <node> [cmd...]   ssh as user lab;   nx <node> '<cmd>'   run as root;   nxi <node>   root script on stdin
# shellcheck disable=SC2046
nssh() { local ip; ip=$(node_ip "$1"); [ -n "$ip" ] || die "unknown node: $1"; shift; ssh $(ssh_opts) "lab@$ip" "$@"; }
nx()   { local n=$1; shift; nssh "$n" "sudo -n bash -c $(printf '%q' "$*")"; }
nxi()  { nssh "$1" sudo -n bash -s; }

ensure_key() {
  [ -f "$LAB_KEY" ] || ssh-keygen -q -t ed25519 -N '' -C k8slab-from-desktop -f "$LAB_KEY"
}
ensure_pycdlib() {
  [ -f "$PYCDLIB_WHL" ] && return
  mkdir -p "$(dirname "$PYCDLIB_WHL")"
  info "downloading pycdlib $PYCDLIB_VERSION (seed ISO builder)"
  fetch "$PYCDLIB_URL" "$PYCDLIB_WHL" "$PYCDLIB_SHA256"
}
mkseed() { ensure_pycdlib; PYTHONPATH="$PYCDLIB_WHL" python3 "$LAB_DIR/tools/mkseed.py" "$@"; }
crlf() { sed 's/\r*$/\r/' "$1" > "$2"; }

# ---------------------------------------------------------------- vm kit ----
vm_kit() {
  local f vbox="$LAB_DIR/infra/vbox"
  ensure_key
  # infra/vbox is itself a complete kit (committed: run it from a git checkout on the VirtualBox host);
  # .state/kit is a CRLF copy for the shared folder / manual copying.
  mkseed --nodes "$NODES_CSV" --pubkey "$LAB_KEY.pub" --out "$vbox/seed.iso" >/dev/null
  {
    echo "# generated by ./lab vm kit from versions.env - KEY=value, no quotes (read by k8slab.bat and k8slab.sh)"
    echo "IMAGE_URL=$UBUNTU_VMDK_URL"
    echo "IMAGE_SHA256=$UBUNTU_VMDK_SHA256"
    echo "IMAGE_FILE=ubuntu-24.04-cloudimg-$UBUNTU_RELEASE.vmdk"
    echo "BASE_DISK=k8slab-base-$UBUNTU_RELEASE.vdi"
    echo "DISK_MB=$VM_DISK_MB"
    echo "VM_GROUP=$VM_GROUP"
    echo "HOSTONLY_IP=$HOSTONLY_IP"
    echo "HOSTONLY_NET=$HOSTONLY_NET"
  } > "$vbox/kit.env"
  rm -rf "$KIT_DIR"; mkdir -p "$KIT_DIR"
  for f in kit.env nodes.csv k8slab.bat; do crlf "$vbox/$f" "$KIT_DIR/$f"; done
  crlf "$vbox/README.md" "$KIT_DIR/README.txt"
  cp "$vbox/seed.iso" "$KIT_DIR/seed.iso"
  install -m 755 "$vbox/k8slab.sh" "$KIT_DIR/k8slab.sh"
  ok "kit refreshed in $(rel "$vbox") (commit it to run from a git checkout) and $(rel "$KIT_DIR")"
  if ! git -C "$LAB_DIR" diff --quiet -- infra/vbox/kit.env infra/vbox/seed.iso 2>/dev/null; then
    warn "infra/vbox/kit.env or seed.iso changed - commit them before fetching on the VirtualBox host"
  fi

  if [ -d "$SHARED_KIT" ] || mkdir -p "$SHARED_KIT" 2>/dev/null; then
    if [ -w "$SHARED_KIT" ]; then
      for f in "$KIT_DIR"/*; do cp "$f" "$SHARED_KIT/" || die "could not copy $f to $SHARED_KIT"; done
      ok "copied to the shared folder $SHARED_KIT"
      echo "   On Windows, open that folder (the host side of the VirtualBox shared folder) and run:  k8slab.bat create"
      return
    fi
  fi
  cat <<EOF
   To get the kit to the VirtualBox host, either:
   - commit + push, then on Windows in your clone:  kubernetes-lab\infra\vbox\k8slab.bat create
   - or copy $(rel "$KIT_DIR") there yourself
   - or let this command copy it into the shared folder ${SHARED_KIT%/*} (not writable for $(id -un) now):
     sudo usermod -aG vboxsf $(id -un), log out and in, run ./lab vm kit again
EOF
}

# --------------------------------------------------------------- vm wait ----
# vm_wait [nodes...]: wait until every node answers SSH with the right identity and cloud-init is done
vm_wait() {
  local n ip t0 deadline=$((SECONDS + ${LAB_WAIT:-900})) out host failed=0
  local -a nodes
  mapfile -t nodes < <(nodes_or_default "$@")
  ensure_key
  for n in "${nodes[@]}"; do
    ip=$(node_ip "$n"); t0=$SECONDS
    printf '  %-8s %-15s ' "$n" "$ip"
    until nssh "$n" true 2>/dev/null; do
      if [ $SECONDS -ge $deadline ]; then echo "${C_R}no SSH${C_0}"; failed=1; continue 2; fi
      sleep 5
    done
    out=$(nssh "$n" 'hostname; cloud-init status --wait >/dev/null 2>&1; cloud-init status 2>/dev/null | sed -n "s/^status: //p"; ip -4 -br addr | grep -c " '"$ip"'/"' 2>/dev/null) || true
    host=$(sed -n 1p <<<"$out")
    if [ "$host" != "$n" ]; then echo "${C_R}hostname is '$host'${C_0} (identity: NIC2 MAC must be $(node_field "$n" 6))"; failed=1
    elif [ "$(sed -n 2p <<<"$out")" != "done" ]; then echo "${C_R}cloud-init: $(sed -n 2p <<<"$out")${C_0} (see: ./lab node $n sudo cloud-init status --long)"; failed=1
    elif [ "$(sed -n 3p <<<"$out")" != 1 ]; then echo "${C_R}$ip is not configured on any NIC${C_0}"; failed=1
    else echo "${C_G}ready${C_0} ($((SECONDS - t0)) s)"; fi
  done
  [ $failed = 0 ] || die "some nodes are not ready"
  ok "all nodes ready"
}

# ------------------------------------------------------------- vm status ----
vm_status() {
  local n ip r line up mem disk
  printf '%-8s %-15s %-13s %-5s %-24s %-10s %s\n' NODE IP ROLE SSH UPTIME MEM-USED DISK-USED
  while read -r n _ _ ip _ _ r; do
    # </dev/null: ssh must not swallow the rest of node_rows from the loop's stdin
    if line=$(nssh "$n" 'echo "$(uptime -p | sed "s/^up //") | $(free -m | awk "/Mem/{printf \"%d/%dM\", \$3, \$2}") | $(df -h / | awk "NR==2{print \$3\"/\"\$2}")"' 2>/dev/null </dev/null); then
      IFS='|' read -r up mem disk <<<"$line"
      printf '%-8s %-15s %-13s %-5s %-24s %-10s %s\n' "$n" "$ip" "$r" "${C_G}up${C_0}" "${up% }" "${mem# }" "${disk# }"
    else
      printf '%-8s %-15s %-13s %-5s\n' "$n" "$ip" "$r" "${C_R}--${C_0}"
    fi
  done < <(node_rows)
}

# -------------------------------------------------------------- vm check ----
# Prerequisites on THIS desktop VM (the VirtualBox side is checked by: k8slab.bat check)
vm_check() {
  local ok_=1 gw; gw=$(node_ip gw)
  # The desktop needs no host-only NIC: through VirtualBox NAT, the Windows host routes 192.168.56.0/24
  # (the nodes then see it as 192.168.56.1). A host-only Adapter 2 works too (then .101+).
  if ip -4 -br addr | grep -q ' 192\.168\.56\.'; then
    ok "desktop VM has a host-only address ($(ip -4 -br addr | awk '/ 192\.168\.56\./{print $3}'))"
  else
    ok "desktop VM reaches 192.168.56.0/24 through VirtualBox NAT and the host (nodes see it as $HOSTONLY_IP)"
  fi
  if nssh gw true 2>/dev/null </dev/null; then ok "k8s-gw ($gw) answers SSH"
  else warn "k8s-gw ($gw) does not answer SSH - created and started? (k8slab.bat status on the VirtualBox host)"; ok_=0; fi
  ensure_key; ok "SSH key $(rel "$LAB_KEY") present"
  if [ -f "$KIT_DIR/seed.iso" ]; then ok "kit built ($(rel "$KIT_DIR"))"; else warn "kit not built yet: ./lab vm kit"; ok_=0; fi
  if [ -w "$SHARED_KIT" ] || [ -w "${SHARED_KIT%/*}" ]; then ok "shared folder ${SHARED_KIT%/*} is writable"
  else warn "shared folder ${SHARED_KIT%/*} not writable (optional: sudo usermod -aG vboxsf $(id -un))"; fi
  [ $ok_ = 1 ]
}

# ----------------------------------------------------------- vm seedtest ----
# Boot the cached Ubuntu image (same build as the kit's VMDK) with the seed under QEMU *software
# emulation* (TCG - no /dev/kvm, no nested virtualization) and check user, key, hostname and static IP.
SEEDTEST_UNIT=k8slab-seedtest
vm_seedtest() {
  local node; node=$(node_name "${1:-cp1}")
  local d="$STATE_DIR/seedtest" img="$CACHE_DIR/noble.img" mac1 mac2 ip out deadline
  [ -n "$(node_ip "$node")" ] || die "unknown node: $node"
  ensure_key
  if [ ! -f "$img" ]; then info "downloading the Ubuntu image for the test"; fetch "$UBUNTU_IMG_URL" "$img" "$UBUNTU_IMG_SHA256"; fi
  rm -rf "$d"; mkdir -p "$d"
  mkseed --nodes "$NODES_CSV" --pubkey "$LAB_KEY.pub" --out "$d/seed.iso" >/dev/null
  qemu-img create -q -f qcow2 -F qcow2 -b "$img" "$d/disk.qcow2" 10G
  mac1=$(node_field "$node" 5 | sed 's/../&:/g; s/:$//'); mac2=$(node_field "$node" 6 | sed 's/../&:/g; s/:$//')
  ip=$(node_ip "$node")
  systemctl --user stop "$SEEDTEST_UNIT" 2>/dev/null || true
  info "booting $node's identity under QEMU/TCG (software emulation, ~5-10 min)"
  systemd-run --user --quiet --unit="$SEEDTEST_UNIT" --collect -p MemoryMax=3G -p CPUQuota=300% \
    qemu-system-x86_64 -accel tcg,thread=multi -machine pc -cpu max -smp 2 -m 2048 -display none -no-reboot \
    -drive "file=$d/disk.qcow2,if=virtio,cache=unsafe" -drive "file=$d/seed.iso,media=cdrom,if=ide,readonly=on" \
    -netdev user,id=n1,hostfwd=tcp:127.0.0.1:2299-:22 -device "e1000,netdev=n1,mac=$mac1,addr=3" \
    -netdev user,id=n2,restrict=on -device "e1000,netdev=n2,mac=$mac2,addr=8" \
    -serial "file:$d/console.log"
  deadline=$((SECONDS + 1200))
  # shellcheck disable=SC2046
  until out=$(ssh $(ssh_opts) -p 2299 lab@127.0.0.1 \
          'cloud-init status --wait >/dev/null; hostname; ip -4 -br addr | grep -c " '"$ip"'/"; sudo -n true && echo sudo; cloud-init status | sed -n "s/^status: //p"' 2>/dev/null); do
    systemctl --user is-active --quiet "$SEEDTEST_UNIT" || die "QEMU exited - see $d/console.log"
    [ $SECONDS -lt $deadline ] || { systemctl --user stop "$SEEDTEST_UNIT"; die "no SSH after 20 min - see $d/console.log"; }
    sleep 10
  done
  systemctl --user stop "$SEEDTEST_UNIT" 2>/dev/null || true
  rm -f "$d/disk.qcow2"   # keep only seed.iso and console.log
  CHECKS_FAILED=0
  check "ssh as lab with $(rel "$LAB_KEY")" true
  check "hostname is $node" test "$(sed -n 1p <<<"$out")" = "$node"
  check "$ip configured on the host-only NIC (MAC $mac2)" test "$(sed -n 2p <<<"$out")" = 1
  check "passwordless sudo" test "$(sed -n 3p <<<"$out")" = sudo
  check "cloud-init finished without errors" test "$(sed -n 4p <<<"$out")" = "done"
  verdict
}

# ---------------------------------------------------------------- health ----
# Desktop health log while the VMs work: load, memory, a journal write probe, gw ping.
health_start() {
  systemctl --user reset-failed k8slab-health 2>/dev/null || true
  systemctl --user is-active --quiet k8slab-health && return 0
  systemd-run --user --quiet --unit=k8slab-health --collect \
    bash "$LAB_DIR/lib/health-watch.sh" "$STATE_DIR/health.log" "$(node_ip gw)"
}
health_stop() { systemctl --user stop k8slab-health 2>/dev/null || true; }
